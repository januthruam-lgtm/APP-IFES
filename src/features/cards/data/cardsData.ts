export const CARDS_MAP: Record<string, CardDefinition> = (() => {
  const map: Record<string, CardDefinition> = {};
  for (const col of COLLECTIONS_DATA) {
    for (const card of col.cards) {
      map[card.id] = card;
    }
  }
  return map;
})();

export const COLLECTIONS_MAP: Record<string, CardAlbumCollection> = (() => {
  const map: Record<string, CardAlbumCollection> = {};
  for (const col of COLLECTIONS_DATA) {
    map[col.id] = col;
  }
  return map;
})();

